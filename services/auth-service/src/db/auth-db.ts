import { drizzleAdapter } from 'better-auth/adapters/drizzle';
import { createDb } from '@notio/db';
import type { Bindings } from '../env';
import * as authSchema from './auth-schema.generated';

/**
 * Better Auth's internal adapter requests joins with boolean flags, e.g. `{ user: true }`.
 * When `@better-auth/drizzle-adapter` receives `true` without `relation: 'one-to-one'`,
 * its `getJoinRelationKey` falls back to pluralising the model name (`users`), which
 * breaks relational lookups because Drizzle's relation on `session` is `user: one(user)`.
 * Marking singular relationships as `one-to-one` tells the adapter to look up the
 * singular relation key `user` defined in Drizzle schema.
 */
function normalizeJoin<T extends Record<string, unknown>>(join: T | undefined): T | undefined {
  if (!join) {
    return join;
  }

  const normalized: Record<string, unknown> = {};

  for (const [key, value] of Object.entries(join)) {
    if (value === true && (key === 'user' || key === 'session')) {
      normalized[key] = { relation: 'one-to-one' };
    } else {
      normalized[key] = value;
    }
  }

  return normalized as T;
}

/**
 * Database adapter for Better Auth: Drizzle over the D1 binding.
 *
 * The schema is generated by `@better-auth/cli generate` and stores fields in
 * snake_case, so Better Auth's native D1 adapter (which expects camelCase) does
 * not work here. The schema file is reused only through CLI regeneration.
 */
export function createAuthDatabase(env: Bindings) {
  const factory = drizzleAdapter(createDb(env, authSchema), {
    provider: 'sqlite',
    schema: authSchema,
  });

  return (options: Parameters<typeof factory>[0]) => {
    const adapter = factory(options);

    return {
      ...adapter,
      findOne: (data: Parameters<typeof adapter.findOne>[0]) =>
        adapter.findOne(
          data.join ? { ...data, join: normalizeJoin(data.join) as typeof data.join } : data,
        ),
      findMany: (data: Parameters<typeof adapter.findMany>[0]) =>
        adapter.findMany(
          data.join ? { ...data, join: normalizeJoin(data.join) as typeof data.join } : data,
        ),
    };
  };
}
