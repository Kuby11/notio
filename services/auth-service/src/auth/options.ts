import type { BetterAuthOptions, SecondaryStorage } from 'better-auth';
import { betterAuth } from 'better-auth';
import { jwt } from 'better-auth/plugins';
import type { Bindings } from '../env';
import { requireAuthSecret } from '../env';
import type { MailSender } from './mailer';
import { sessionPasswordPlugin } from './session-password-plugin';

export const AUTH_BASE_PATH = '/api/auth';

/** Endpoint with the public keys: the gateway verifies token signatures against it. */
export const JWKS_PATH = '/api/auth/jwks';

/** Endpoint that issues a JWT for the active session. */
export const TOKEN_PATH = '/api/auth/token';

export interface AuthDependencies {
  mailSender: MailSender;
  /** What links point at: in dev, the local frontend. */
  publicUrl: string;
  frontendUrl: string;
  /**
   * Database adapter. In Workers it is Drizzle over D1 with the generated schema
   * (`@better-auth/cli generate`); in the CLI it is a stub for schema generation.
   */
  database: BetterAuthOptions['database'];
  /** KV for rate limits and the cookie cache. */
  secondaryStorage: SecondaryStorage;
  log?: (message: string) => void;
}

const DEFAULT_RATE_LIMIT_MAX = 20;
const DEFAULT_RATE_LIMIT_WINDOW_SECONDS = 60;

function positiveInt(value: string | undefined, fallback: number): number {
  const parsed = Number.parseInt(value ?? '', 10);

  return Number.isFinite(parsed) && parsed > 0 ? parsed : fallback;
}

/**
 * Rewrites callbackURL in Better Auth links to the frontend address.
 *
 * Better Auth builds links with callbackURL=/ (relative to its own baseURL,
 * i.e. the gateway). Without the rewrite, a user landing after email
 * confirmation or a password reset ends up at the gateway root, not the frontend.
 */
function rewriteCallbackUrl(url: string, frontendUrl: string): string {
  try {
    const parsed = new URL(url);

    parsed.searchParams.set('callbackURL', frontendUrl);

    return parsed.toString();
  } catch {
    return url;
  }
}

/**
 * An OAuth provider is enabled only when its client id and secret exist:
 * without them Better Auth must neither fail at startup nor offer a login
 * that cannot be completed.
 */
function socialProviders(env: Bindings): NonNullable<BetterAuthOptions['socialProviders']> {
  const providers: NonNullable<BetterAuthOptions['socialProviders']> = {};

  if (env.GITHUB_CLIENT_ID && env.GITHUB_CLIENT_SECRET) {
    providers.github = {
      clientId: env.GITHUB_CLIENT_ID,
      clientSecret: env.GITHUB_CLIENT_SECRET,
    };
  }

  if (env.GOOGLE_CLIENT_ID && env.GOOGLE_CLIENT_SECRET) {
    providers.google = {
      clientId: env.GOOGLE_CLIENT_ID,
      clientSecret: env.GOOGLE_CLIENT_SECRET,
    };
  }

  return providers;
}

/**
 * Origins the service trusts: its own address plus explicitly listed ones.
 *
 * Better Auth checks Origin on mutating requests: without the list, a login
 * from the frontend on another port would count as a forgery (CSRF protection).
 */
function trustedOrigins(env: Bindings, publicUrl: string): string[] {
  const own = new URL(publicUrl).origin;
  const extra = (env.TRUSTED_ORIGINS ?? '')
    .split(',')
    .map((origin) => origin.trim())
    .filter((origin) => origin.length > 0);

  return [...new Set([own, ...extra])];
}

/**
 * The single builder of Better Auth options.
 *
 * The function is pure: it touches no database and needs no Workers
 * environment. For the same reason the CLI uses it to generate the schema
 * (`@better-auth/cli generate`), which runs in Node.
 */
export function buildAuthOptions(env: Bindings, deps: AuthDependencies): BetterAuthOptions {
  const log = deps.log ?? ((message: string) => console.log(message));
  const frontendUrl = deps.frontendUrl.replace(/\/+$/u, '');
  const providers = socialProviders(env);

  return {
    appName: 'notio',
    baseURL: deps.publicUrl,
    basePath: AUTH_BASE_PATH,
    secret: requireAuthSecret(env),

    // Database: Drizzle over D1 with the schema generated by the Better Auth CLI.
    database: deps.database,

    // Rate limit counters live in KV rather than isolate memory: the same
    // user lands on different Workers instances.
    secondaryStorage: deps.secondaryStorage,

    // The session lives only in an httpOnly cookie; the browser cannot read the token.
    // The cookie cache is deliberately off: after sign-out, cached
    // session data would keep serving the user for several more minutes.
    // Reading the session from D1 is local and fast enough.
    session: {
      expiresIn: 60 * 60 * 24 * 7,
      updateAge: 60 * 60 * 24,
      cookieCache: { enabled: false },
    },

    emailAndPassword: {
      enabled: true,
      requireEmailVerification: true,
      minPasswordLength: 12,
      maxPasswordLength: 128,
      autoSignIn: false,
      sendResetPassword: async ({ user, url }) => {
        await deps.mailSender.send({
          to: user.email,
          kind: 'RESET_PASSWORD',
          subject: 'Reset your password for notio',
          // Better Auth builds the link with callbackURL=/ (gateway). Rewrite it to the frontend
          // so a password reset lands on the login page.
          actionUrl: rewriteCallbackUrl(url, deps.frontendUrl),
        });
      },
    },

    emailVerification: {
      sendOnSignUp: true,
      sendOnSignIn: true,
      autoSignInAfterVerification: true,
      expiresIn: 60 * 60 * 24,
      sendVerificationEmail: async ({ user, url }) => {
        try {
          await deps.mailSender.send({
            to: user.email,
            kind: 'VERIFY_EMAIL',
            subject: 'Confirm your email for notio',
            // Better Auth builds the link with callbackURL=/ (gateway). Rewrite it to the frontend
            // so email confirmation lands on the home page.
            actionUrl: rewriteCallbackUrl(url, deps.frontendUrl),
          });
        } catch (error) {
          // Better Auth runs this as a background task and logs the error as
          // an empty object (Error fields are not enumerable): the reason —
          // e.g. the provider's response text — must be logged explicitly.
          log(
            JSON.stringify({
              level: 'error',
              service: 'auth-service',
              event: 'mail_send_failed',
              to: user.email,
              reason: error instanceof Error ? error.message : String(error),
            }),
          );

          throw error;
        }
      },
    },

    // Account self-service. An email change is confirmed by a link sent to the
    // new address (the generic sendVerificationEmail above); account deletion
    // asks for a fresh session, so a hijacked tab cannot wipe the account.
    user: {
      changeEmail: {
        enabled: true,
      },
      deleteUser: {
        enabled: true,
      },
    },

    socialProviders: providers,

    // A user who registered with a password and then picks "Sign in with
    // Google" has two accounts under one address. Without explicit trust the
    // link is refused and the OAuth round trip ends in an error, so the
    // configured providers are trusted by name: the email they return is
    // verified on their side. The local account still has to be verified
    // itself (Better Auth's `requireLocalEmailVerified` default) — trust in a
    // provider must not turn an unconfirmed address into a takeover.
    account: {
      accountLinking: {
        enabled: true,
        trustedProviders: Object.keys(providers),
      },
    },

    // No session is created for requests with a foreign Origin: CSRF protection
    // at the origin level, not only at the SameSite level.
    trustedOrigins: trustedOrigins(env, deps.publicUrl),

    // The gateway has no UI: its own /api/auth/error page is a dead end the
    // user cannot leave. Every auth error is sent back to the app instead, with
    // `?error=<code>` so the form can explain what happened.
    onAPIError: {
      errorURL: `${frontendUrl}/login`,
    },

    rateLimit: {
      enabled: true,
      window: positiveInt(env.RATE_LIMIT_WINDOW_SECONDS, DEFAULT_RATE_LIMIT_WINDOW_SECONDS),
      max: positiveInt(env.RATE_LIMIT_MAX_REQUESTS, DEFAULT_RATE_LIMIT_MAX),
      storage: 'secondary-storage',
    },

    // The JWT is needed for service-to-service calls: the gateway verifies the
    // signature locally against JWKS and does not call auth-service on every request.
    plugins: [
      jwt({
        jwks: {
          // In production the private key is encrypted with the service secret: even after a
          // database leak it cannot be used. In dev encryption is off so that
          // changing BETTER_AUTH_SECRET does not break already issued JWKS keys.
          disablePrivateKeyEncryption: env.ENVIRONMENT !== 'production',
        },
      }),
      sessionPasswordPlugin(),
    ],

    advanced: {
      useSecureCookies: env.ENVIRONMENT === 'production',
      cookiePrefix: 'notio',
      // Web and gateway are sibling hosts (workers.dev subdomains): the session
      // cookie must be set on their shared parent domain, otherwise it stays on
      // the gateway host and proxy.ts on the web worker never sees
      // authenticated navigation. COOKIE_DOMAIN sets that domain; in dev both
      // hosts are localhost (the cookie ignores ports), so no domain is needed.
      ...(env.COOKIE_DOMAIN
        ? {
            crossSubDomainCookies: {
              enabled: true,
              domain: env.COOKIE_DOMAIN,
            },
          }
        : {}),
      database: {
        // User and session ids are UUIDs: internal services
        // accept ids only as UUIDs from the shared contract.
        generateId: 'uuid',
      },
      ipAddress: {
        // We count by the IP Cloudflare sets, not by
        // headers a client could forge.
        ipAddressHeaders: ['cf-connecting-ip'],
      },
    },

    logger: {
      level: env.ENVIRONMENT === 'production' ? 'error' : 'warn',
      log(level, message, ...args) {
        log(JSON.stringify({ level, service: 'auth-service', message, args }));
      },
    },
  };
}

export { betterAuth };
